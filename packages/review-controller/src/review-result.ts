import { z } from "zod";

export const REVIEW_CATEGORIES = [
  "exfiltration",
  "backdoor",
  "supply_chain",
  "obfuscation",
  "cryptomining",
  "hidden_functionality",
] as const;

const categorySchema = z.enum(REVIEW_CATEGORIES);
const coverageStatusSchema = z.enum(["clean", "findings", "incomplete"]);
const pathSchema = z
  .string()
  .min(1)
  .max(4096)
  .refine(
    (path) => !path.startsWith("/") && !path.includes("\0") && !path.split("/").includes(".."),
    "Expected a repository-relative path"
  );

export const reviewResultSchema = z.strictObject({
  schemaVersion: z.literal(1),
  verdict: z.enum(["CLEAN", "SUSPICIOUS", "MALICIOUS"]),
  findings: z
    .array(
      z.strictObject({
        category: categorySchema,
        path: pathSchema,
        line: z.number().int().positive(),
        evidence: z.string().trim().min(1).max(8192),
        explanation: z.string().trim().min(1).max(8192),
      })
    )
    .max(1000),
  coverage: z.strictObject({
    exfiltration: coverageStatusSchema,
    backdoor: coverageStatusSchema,
    supply_chain: coverageStatusSchema,
    obfuscation: coverageStatusSchema,
    cryptomining: coverageStatusSchema,
    hidden_functionality: coverageStatusSchema,
  }),
  reviewedPaths: z.array(pathSchema).max(10_000),
  incompleteReasons: z.array(z.string().trim().min(1).max(4096)).max(1000),
});

export type ReviewResult = z.infer<typeof reviewResultSchema>;

/** Generated by the controller from the immutable comparison, never by the agent. */
export interface ReviewManifestEntry {
  path: string;
  reviewable: boolean;
}

export type ReviewEvaluation =
  | { outcome: "clean"; verdict: "CLEAN"; result: ReviewResult }
  | { outcome: "finding"; verdict: "SUSPICIOUS" | "MALICIOUS"; result: ReviewResult }
  | {
      outcome: "incomplete";
      reason:
        | "RESULT_TOO_LARGE"
        | "INVALID_RESULT"
        | "UNREVIEWABLE_SCOPE"
        | "INCOMPLETE_COVERAGE"
        | "INCONSISTENT_RESULT";
    };

const MAX_RESULT_BYTES = 1024 * 1024;

/**
 * Evaluates only the contents of an authenticated terminal assistant response.
 * The caller must first establish successful execution and exact attempt/session
 * binding. This function cannot turn an unsuccessful execution into a verdict.
 */
export function evaluateReviewResult(
  response: string,
  manifest: readonly ReviewManifestEntry[]
): ReviewEvaluation {
  if (Buffer.byteLength(response, "utf8") > MAX_RESULT_BYTES) {
    return { outcome: "incomplete", reason: "RESULT_TOO_LARGE" };
  }
  let raw: unknown;
  try {
    raw = JSON.parse(response);
  } catch {
    return { outcome: "incomplete", reason: "INVALID_RESULT" };
  }
  const parsed = reviewResultSchema.safeParse(raw);
  if (!parsed.success) return { outcome: "incomplete", reason: "INVALID_RESULT" };
  const result = parsed.data;
  if (manifest.some((entry) => !entry.reviewable)) {
    return { outcome: "incomplete", reason: "UNREVIEWABLE_SCOPE" };
  }
  const expected = new Set(manifest.map((entry) => entry.path));
  const reviewed = new Set(result.reviewedPaths);
  if (
    reviewed.size !== result.reviewedPaths.length ||
    reviewed.size !== expected.size ||
    [...expected].some((path) => !reviewed.has(path)) ||
    result.incompleteReasons.length > 0 ||
    REVIEW_CATEGORIES.some((category) => result.coverage[category] === "incomplete")
  ) {
    return { outcome: "incomplete", reason: "INCOMPLETE_COVERAGE" };
  }
  const categoriesWithFindings = new Set(result.findings.map((finding) => finding.category));
  if (
    (result.verdict === "CLEAN") !== (result.findings.length === 0) ||
    REVIEW_CATEGORIES.some(
      (category) =>
        (result.coverage[category] === "findings") !== categoriesWithFindings.has(category)
    )
  ) {
    return { outcome: "incomplete", reason: "INCONSISTENT_RESULT" };
  }
  return result.verdict === "CLEAN"
    ? { outcome: "clean", verdict: result.verdict, result }
    : { outcome: "finding", verdict: result.verdict, result };
}
